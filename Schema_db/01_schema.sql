BEGIN
   EXECUTE IMMEDIATE 'DROP TABLE article_tags CASCADE CONSTRAINTS';
   EXECUTE IMMEDIATE 'DROP TABLE article_categories CASCADE CONSTRAINTS';
   EXECUTE IMMEDIATE 'DROP TABLE comments CASCADE CONSTRAINTS';
   EXECUTE IMMEDIATE 'DROP TABLE articles CASCADE CONSTRAINTS';
   EXECUTE IMMEDIATE 'DROP TABLE categories CASCADE CONSTRAINTS';
   EXECUTE IMMEDIATE 'DROP TABLE tags CASCADE CONSTRAINTS';
   EXECUTE IMMEDIATE 'DROP TABLE users CASCADE CONSTRAINTS';
EXCEPTION
   WHEN OTHERS THEN
      IF SQLCODE != -942 THEN
         RAISE;
      END IF;
END;
/

-- -----------------------------------------------------
-- 1. Entidades principales
-- -----------------------------------------------------

-- Usuarios que pueden ser autores de artículos y comentarios.
CREATE TABLE users (
    id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR2(100) NOT NULL,
    email VARCHAR2(150) NOT NULL UNIQUE
);

-- Artículos publicados. CLOB permite almacenar textos extensos.
CREATE TABLE articles (
    id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title    VARCHAR2(200) NOT NULL,
    pub_date DATE DEFAULT SYSDATE,
    text     CLOB,
    user_id  NUMBER NOT NULL,
    CONSTRAINT fk_articles_user FOREIGN KEY (user_id)
        REFERENCES users(id) ON DELETE CASCADE
);

-- Comentarios asociados a un usuario y a un artículo.
CREATE TABLE comments (
    id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content       CLOB,
    creation_date DATE DEFAULT SYSDATE,
    user_id       NUMBER NOT NULL,
    article_id    NUMBER NOT NULL,
    CONSTRAINT fk_comments_user FOREIGN KEY (user_id)
        REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_comments_article FOREIGN KEY (article_id)
        REFERENCES articles(id) ON DELETE CASCADE
);

-- Etiquetas reutilizables para clasificar artículos.
CREATE TABLE tags (
    id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100) NOT NULL,
    url  VARCHAR2(200)
);

-- Categorías reutilizables para clasificar artículos.
CREATE TABLE categories (
    id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100) NOT NULL,
    url  VARCHAR2(200)
);

-- -----------------------------------------------------
-- 2. Relaciones muchos-a-muchos
-- -----------------------------------------------------

-- Un artículo puede tener varias etiquetas y una etiqueta puede pertenecer
-- a varios artículos. La clave compuesta evita asociaciones duplicadas.
CREATE TABLE article_tags (
    article_id NUMBER NOT NULL,
    tag_id     NUMBER NOT NULL,
    CONSTRAINT pk_article_tags PRIMARY KEY (article_id, tag_id),
    CONSTRAINT fk_at_article FOREIGN KEY (article_id)
        REFERENCES articles(id) ON DELETE CASCADE,
    CONSTRAINT fk_at_tag FOREIGN KEY (tag_id)
        REFERENCES tags(id) ON DELETE CASCADE
);

-- Un artículo puede pertenecer a varias categorías y viceversa.
CREATE TABLE article_categories (
    article_id  NUMBER NOT NULL,
    category_id NUMBER NOT NULL,
    CONSTRAINT pk_article_categories PRIMARY KEY (article_id, category_id),
    CONSTRAINT fk_ac_article FOREIGN KEY (article_id)
        REFERENCES articles(id) ON DELETE CASCADE,
    CONSTRAINT fk_ac_category FOREIGN KEY (category_id)
        REFERENCES categories(id) ON DELETE CASCADE
);

